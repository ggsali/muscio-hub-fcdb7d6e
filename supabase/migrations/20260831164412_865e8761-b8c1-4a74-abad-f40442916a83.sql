$md$# PLA vs. PETG: Welches Material für Ihren 3D-Druck?

PLA und PETG sind die beiden häufigsten Materialien im FDM-3D-Druck. Kurz gesagt: **PLA für günstige, formstabile Teile im Innenbereich – PETG für Teile, die Feuchtigkeit, Wärme oder mechanische Belastung aushalten müssen.**

## PLA im Überblick

PLA (Polylactid) ist das Standardmaterial im 3D-Druck. Es druckt sauber, verzieht sich kaum und liefert scharfe Details.

**Vorteile**
- Günstigstes Material (ab CHF 0.04/g)
- Sehr gute Detailtreue und Maßhaltigkeit
- Grosse Farbauswahl, auch matt und seidenmatt
- Aus nachwachsenden Rohstoffen

**Nachteile**
- Weich ab ca. 55–60 °C – nicht fürs Auto oder direkte Sonne
- Spröder Bruch bei Schlagbelastung
- Nicht dauerhaft feuchtigkeitsbeständig

**Typische Anwendungen:** Anschauungsmodelle, Designprototypen, Präsentationsteile, Halterungen im Innenbereich, Architekturmodelle.

## PETG im Überblick

PETG ist der technische Allrounder. Es ist zäher als PLA, hält Feuchtigkeit stand und bleibt bis ca. 75 °C formstabil.

**Vorteile**
- Zäh statt spröde – bricht nicht schlagartig
- Feuchtigkeits- und chemikalienbeständig
- Lebensmittelechte Varianten verfügbar
- Höhere Temperaturbeständigkeit als PLA

**Nachteile**
- Etwas teurer (ab CHF 0.05/g)
- Leicht glänzende Oberfläche, feine Details weniger scharf als bei PLA
- Neigt bei Überhängen zu Fäden (Stringing)

**Typische Anwendungen:** Gehäuse, Ersatzteile, Halterungen mit Belastung, Teile mit Wasserkontakt, Vorrichtungen in der Werkstatt.

