$md$# FDM vs. SLA 3D-Druck: Wann welches Verfahren?

FDM und SLA sind die beiden Verfahren, die wir bei 3DMuscio einsetzen. Die Kurzfassung: **FDM für belastbare Funktionsteile und günstige Prototypen, SLA für Sichtteile mit glatter Oberfläche und feinen Details.**

## FDM (Fused Deposition Modeling)

Ein Kunststofffaden wird geschmolzen und Schicht für Schicht aufgetragen.

**Stärken**
- Robuste, mechanisch belastbare Teile
- Grosse Materialauswahl: PLA, PETG, ABS, ASA, TPU
- Günstig, auch bei grösseren Bauteilen
- Gut geeignet für Kleinserien

**Grenzen**
- Sichtbare Schichten (typisch 0.1–0.3 mm)
- Feine Details begrenzt durch Düsendurchmesser
- Nachbearbeitung nötig, wenn die Oberfläche perfekt sein soll

## SLA (Stereolithografie / Resin)

Flüssiges Harz wird schichtweise mit Licht ausgehärtet.

**Stärken**
- Sehr glatte Oberflächen, Schichten kaum sichtbar
- Feinste Details und dünne Wandstärken
- Ideal für Miniaturen, Modelle und Sichtteile

**Grenzen**
- Sprödere Teile, weniger für dauerhafte mechanische Belastung
- Teurer pro Gramm
- Kleinerer Bauraum, aufwendigere Nachbearbeitung (Waschen, Nachhärten)
- UV-empfindlich, für Aussenbereich ungeeignet

